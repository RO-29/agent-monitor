func TestBgPathAllowed(t *testing.T) {
	root, out := bgFixture(t)
	if err := os.WriteFile(out, []byte("x"), 0o600); err != nil {
		t.Fatal(err)
	}
	if _, _, ok := readBgOutput(out, "bk1x2y3z4"); !ok {
		t.Fatal("valid task file rejected")
	}
	link := filepath.Join(filepath.Dir(out), "blinkxxxx.output")
	secret := filepath.Join(root, "secret")
	_ = os.WriteFile(secret, []byte("s"), 0o600)
	_ = os.Symlink(secret, link)
	other := filepath.Join(root, "claude-"+strconv.Itoa(os.Getuid()), "x", "tasks", "bk1x2y3z4.output")
	for _, c := range []struct{ path, id string }{
		{link, "blinkxxxx"},
		{out, "bother000"},
		{secret, "secret"},
		{other, "bk1x2y3z4"},
		{filepath.Dir(out) + "/../tasks/bk1x2y3z4.output", "bk1x2y3z4"},
		{"/etc/passwd", "passwd"},
		{"tasks/bk1x2y3z4.output", "bk1x2y3z4"},
	} {
		if _, _, ok := readBgOutput(c.path, c.id); ok {
			t.Fatalf("accepted %s", c.path)
		}
	}
	dirLink := filepath.Join(root, "claude-"+strconv.Itoa(os.Getuid()), "-w", "sess-2")
	_ = os.Symlink(t.TempDir(), dirLink)
	_ = os.MkdirAll(filepath.Join(dirLink, "tasks"), 0o700)
	escaped := filepath.Join(dirLink, "tasks", "bk1x2y3z4.output")
	_ = os.WriteFile(escaped, []byte("x"), 0o600)
	if _, _, ok := readBgOutput(escaped, "bk1x2y3z4"); ok {
		t.Fatal("accepted a task dir behind a symlink out of the temp root")
	}
}

func TestBgTailKeepsTheEnd(t *testing.T) {
	long := make([]byte, 0, orchOutputCap*2)
	for i := 0; len(long) < orchOutputCap*2; i++ {
		long = append(long, []byte("line "+strconv.Itoa(i)+"\n")...)
	}
	got := bgTail(string(long), false)
	if len(got) > orchOutputCap+4 || got[:4] != "…\n" || !strings.HasSuffix(string(long), got[4:]+"\n") {
		t.Fatalf("tail %d %q", len(got), got[:20])
	}
}

