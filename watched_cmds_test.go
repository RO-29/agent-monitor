// Synthetic transcripts only: the shapes match what Claude Code and Codex write, the content is invented.

func localCmd(sec int, name, args string) map[string]any {
	return cUser(sec, "<command-name>/"+name+"</command-name>\n            <command-message>"+name+"</command-message>\n            <command-args>"+args+"</command-args>")
}

func promptCmd(sec int, name, args string) map[string]any {
	s := "<command-message>" + name + "</command-message>\n<command-name>/" + name + "</command-name>"
	if args != "" {
		s += "\n<command-args>" + args + "</command-args>"
	}
	return cUser(sec, s)
}

func caveat(sec int) map[string]any {
	return claudeRec("user", sec, map[string]any{"role": "user", "content": "<local-command-caveat>Caveat: generated by local commands.</local-command-caveat>"}, map[string]any{"isMeta": true})
}

func metaText(sec int, text string) map[string]any {
	return claudeRec("user", sec, map[string]any{"role": "user", "content": []any{map[string]any{"type": "text", "text": text}}}, map[string]any{"isMeta": true})
}

func userCmds(items []*OItem) []*OItem {
	var out []*OItem
	for _, it := range items {
		if it.By == "user" {
			out = append(out, it)
		}
	}
	return out
}

func refFor(id, path string, tool Tool) watchedRef {
	return watchedRef{ID: id, Tool: tool, RawID: id, Path: path, Resolved: true}
}

func TestWatchedSlashLocalCommands(t *testing.T) {
	path := filepath.Join(t.TempDir(), "slash.jsonl")
	jsonl(t, path,
		caveat(0),
		localCmd(0, "clear", ""),
		cUser(0, "<local-command-stdout></local-command-stdout>"),
		cUser(1, "Fix the build"),
		cAsst(2, "m1", "end_turn", map[string]any{"type": "text", "text": "Done."}),
		caveat(3),
		localCmd(3, "model", "opus"),
		cUser(3, "<local-command-stdout>Set model to \x1b[1mopus\x1b[22m &amp; saved</local-command-stdout>"),
		localCmd(4, "compact", ""),
		map[string]any{"type": "system", "subtype": "compact_boundary", "timestamp": tsAt(4)},
		claudeRec("user", 4, map[string]any{"role": "user", "content": "This session is being continued."}, map[string]any{"isCompactSummary": true}),
		cUser(5, "<local-command-stdout>\x1b[2mCompacted (ctrl+o to see full summary)\x1b[22m</local-command-stdout>"),
		localCmd(6, "mcp", ""),
		localCmd(7, "cost", ""),
		cUser(7, "<local-command-stderr>Error: no cost data</local-command-stderr>"),
		localCmd(8, "exit", ""),
		cUser(8, "<local-command-stdout>(no content)</local-command-stdout>"),
	)
	res, err := watchedItemsFor(refFor("claude:slash", path, ToolClaude), -1, -1)
	if err != nil {
		t.Fatal(err)
	}
	if len(res.Runs) != 2 {
		t.Fatalf("local commands must not open turns: %d runs", len(res.Runs))
	}
	cmds := userCmds(res.Items)
	want := []struct{ text, cmd, out, status string }{
		{"/clear", "/clear", "", "completed"},
		{"/model", "/model opus", "Set model to opus & saved", "completed"},
		{"/compact", "/compact", "Compacted (ctrl+o to see full summary)", "completed"},
		{"/mcp", "/mcp", "", "completed"},
		{"/cost", "/cost", "Error: no cost data", "failed"},
		{"/exit", "/exit", "", "completed"},
	}
	if len(cmds) != len(want) {
		t.Fatalf("want %d slash commands, got %d (%s)", len(want), len(cmds), kinds(res.Items))
	}
	for i, w := range want {
		c := cmds[i]
		if c.Kind != "command" || c.Text != w.text || c.Command != w.cmd || c.Output != w.out || c.Status != w.status {
			t.Fatalf("command %d: %+v", i, c)
		}
	}
	if res.Items[0].Kind != "command" || res.Items[1].Kind != "user" || res.Items[1].Text != "" {
		t.Fatalf("a leading /clear opens the first turn with an empty prompt: %s", kinds(res.Items))
	}
	if res.Runs[1].Prompt != "Fix the build" {
		t.Fatalf("second turn %+v", res.Runs[1])
	}
}

func TestWatchedSlashPromptCommands(t *testing.T) {
	path := filepath.Join(t.TempDir(), "prompt.jsonl")
	jsonl(t, path,
		cUser(1, "Hello"),
		cAsst(2, "m1", "end_turn", map[string]any{"type": "text", "text": "Hi."}),
		promptCmd(3, "review-pr", "42"),
		metaText(3, "Review pull request 42 and list defects."),
		cAsst(4, "m2", "end_turn", map[string]any{"type": "text", "text": "Reviewed."}),
		promptCmd(5, "style-guide", ""),
		metaText(5, skillBasePrefix+" /skills/style-guide\n\n# Style guide"),
		cAsst(6, "m3", "end_turn", map[string]any{"type": "text", "text": "Loaded."}),
		promptCmd(7, "old-cmd", "x"),
		cUser(7, "Expanded prompt from an older version"),
		cAsst(8, "m4", "end_turn", map[string]any{"type": "text", "text": "Ok."}),
	)
	res, err := watchedItemsFor(refFor("claude:prompt", path, ToolClaude), -1, -1)
	if err != nil {
		t.Fatal(err)
	}
	if len(res.Runs) != 4 {
		t.Fatalf("each prompt command is one turn: %d runs", len(res.Runs))
	}
	byRun := map[string][]*OItem{}
	for _, it := range res.Items {
		byRun[it.RunID] = append(byRun[it.RunID], it)
	}
	check := func(r *ORun, name, cmd, prompt string) {
		t.Helper()
		items := byRun[r.ID]
		if len(items) < 2 || items[0].By != "user" || items[0].Text != name || items[0].Command != cmd || items[1].Kind != "user" || items[1].Text != prompt {
			t.Fatalf("turn %d: %s %+v %+v", r.Index, kinds(items), items[0], items[1])
		}
	}
	check(res.Runs[1], "/review-pr", "/review-pr 42", "Review pull request 42 and list defects.")
	check(res.Runs[2], "/style-guide", "/style-guide", "")
	check(res.Runs[3], "/old-cmd", "/old-cmd x", "Expanded prompt from an older version")
	if res.Runs[1].Prompt != "Review pull request 42 and list defects." || res.Runs[2].Prompt != "/style-guide" {
		t.Fatalf("run prompts %q %q", res.Runs[1].Prompt, res.Runs[2].Prompt)
	}
}

func bgFixture(t *testing.T) (root, outPath string) {
	t.Helper()
	root = t.TempDir()
	if r, err := filepath.EvalSymlinks(root); err == nil {
		root = r
	}
	old := bgTempRoots
	bgTempRoots = func() []string { return []string{root} }
	t.Cleanup(func() { bgTempRoots = old })
	dir := filepath.Join(root, "claude-"+strconv.Itoa(os.Getuid()), "-w", "sess-1", "tasks")
	if err := os.MkdirAll(dir, 0o700); err != nil {
		t.Fatal(err)
	}
	outPath = filepath.Join(dir, "bk1x2y3z4.output")
	return root, outPath
}

func bgMoved(sec int, path string) map[string]any {
	return cUser(sec, "<bash-stdout>Command did not complete within its 120s timeout and was moved to the background (ID: bk1x2y3z4). Output is being written to: "+
		path+". You will be notified when it completes. To check interim output, use Read on that file path.</bash-stdout><bash-stderr></bash-stderr>")
}

func setBgNow(t *testing.T, sec int) {
	old := bgNow
	bgNow = func() time.Time { return time.UnixMilli(parseTimestamp(tsAt(sec))) }
	t.Cleanup(func() { bgNow = old })
}

func TestWatchedBackgroundBang(t *testing.T) {
	_, out := bgFixture(t)
	if err := os.WriteFile(out, []byte("step 1\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	setBgNow(t, 130)
	path := filepath.Join(t.TempDir(), "bg.jsonl")
	jsonl(t, path,
		cUser(1, "Deploy"),
		cAsst(2, "m1", "end_turn", map[string]any{"type": "text", "text": "Ok."}),
		cUser(3, "<bash-input>make deploy</bash-input>"),
		bgMoved(123, out),
	)
	ref := refFor("claude:bg", path, ToolClaude)
	res, err := watchedItemsFor(ref, -1, -1)
	if err != nil {
		t.Fatal(err)
	}
	b := userCmds(res.Items)
	if len(b) != 1 || !b[0].Bg || b[0].Status != "started" || b[0].Output != "step 1" || b[0].Command != "make deploy" {
		t.Fatalf("background command %+v", b)
	}

	f, _ := os.OpenFile(out, os.O_APPEND|os.O_WRONLY, 0)
	_, _ = f.WriteString("step 2 \x1b[32mok\x1b[0m\n")
	f.Close()
	future := time.Now().Add(time.Second)
	_ = os.Chtimes(out, future, future)
	res2, err := watchedItemsFor(ref, res.Cursor, -1)
	if err != nil {
		t.Fatal(err)
	}
	b = userCmds(res2.Items)
	if len(b) != 1 || b[0].Status != "started" || b[0].Output != "step 1\nstep 2 ok" {
		t.Fatalf("growing output not sent on an after poll: %+v", b)
	}

	appendJSONL(t, path, claudeRec("user", 200, map[string]any{"role": "user", "content": "<task-notification>\n<task-id>bk1x2y3z4</task-id>\n<tool-use-id>x</tool-use-id>\n<output-file>" +
		out + "</output-file>\n<status>failed</status>\n<summary>Background command \"make deploy\" failed with exit code 2</summary>\n</task-notification>"}, map[string]any{"origin": map[string]any{"kind": "task-notification"}}))
	res3, err := watchedItemsFor(ref, res2.Cursor, -1)
	if err != nil {
		t.Fatal(err)
	}
	b = userCmds(res3.Items)
	if len(b) != 1 || b[0].Status != "failed" || b[0].ExitCode == nil || *b[0].ExitCode != 2 || b[0].EndedAt != parseTimestamp(tsAt(200)) {
		t.Fatalf("notification did not end the command: %+v", b)
	}
	for _, it := range res3.Items {
		if it.Kind == "user" && it.By == "" {
			t.Fatalf("a task notification is not a prompt: %+v", it)
		}
	}
}

